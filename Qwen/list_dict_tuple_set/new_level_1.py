# Задание 1.5 — Проверка наличия элемента
# Даны:
fruits = ["яблоко", "банан", "апельсин"]
tags = {"smoke", "auth"}
user = {"name": "Анна", "age": 30}


# ✅ Напиши код, который проверяет:

# Есть ли "банан" в fruits?
# Есть ли "ui" в tags?
# Есть ли ключ "email" в user?
# Есть ли значение "Анна" в значениях user?
# 💡 Подсказки:

# для списка/множества: x in container
# для словаря: key in dict → ключи, value in dict.values() → значения

print("банан" in fruits)
print("ui" in tags)
print("email" in user.keys())
print("Анна" in user.values())


