# [выражение for элемент in итерируемый_объект if условие]

# выражение — то, что попадёт в новый список (можно менять элемент, напр., x * 2, x.upper() и т.д.)
# for элемент in итерируемый_объект — цикл по исходной коллекции
# if условие — необязательный фильтр (оставляет только те элементы, для которых условие истинно)


# 🟢 Уровень 1: Основы
# Создай список квадратов чисел от 1 до 10, исключая числа, делящиеся на 3.

list_num = [x**2 for x in range(1, 11) if x % 3 != 0]
print(list_num)


# Из списка имён ['Анна', 'Мария', 'Олег', 'Елена'] сделай список имён длиной более 4 букв, в нижнем регистре.

names = ['Анна', 'Мария', 'Олег', 'Елена']

new_names = [x.lower() for x in names if len(x) > 4]
print(new_names)


# Дан список: [1, -2, 3, -4, 5, -6]. Получи список модулей отрицательных чисел.
nums = [1, -2, 3, -4, 5, -6]
abs_nums = [x * (-1) for x in nums if x < 0]
print(abs_nums)


# 🟡 Уровень 2: Условия и преобразования
# Создай список всех пар (x, y), где x ∈ [1, 2, 3], y ∈ [10, 20], и x + y > 20

pair_x = [1, 2, 3]
pair_y = [10, 20]
pair = [(x, y) for x in pair_x for y in pair_y if x + y > 20]
print(pair)


# Есть строка: "Привет, мир и Python!". Создай список только букв (без знаков препинания и пробелов), в верхнем регистре.
# Подсказка: используй char.isalpha().

string = "Привет, мир и Python!"
list_st = [x.upper() for x in string if x.isalpha()]
print(list_st)

# Из списка слов ['cat', 'dog', 'elephant', 'ant'] получи список слов, длина которых кратна 3,
# и каждое слово повтори 2 раза (например, 'cat' → 'catcat').
words = ['cat', 'dog', 'elephant', 'ant']
new_words = [x+x for x in words if len(x) % 3 == 0]
print(new_words)


# 🔴 Уровень 3: Вложенные и с dict/set

# Есть список словарей
students = [
    {'name': 'Анна', 'grade': 85},
    {'name': 'Борис', 'grade': 72},
    {'name': 'Вера', 'grade': 93}
]
# Используя list comprehension, получи список имён студентов со средним баллом ≥ 80.
list_students = [x["name"] for x in students if x["grade"] >= 80]
print(list_students)

# (Не list comprehension, но для контраста) Перепиши задание 1 с помощью:
# обычного for-цикла и .append()
# Создай список квадратов чисел от 1 до 10, исключая числа, делящиеся на 3.
# map/filter (с лямбдами)
lists = []
for x in range(1, 11):
    if not x % 3 == 0:
        kv_x = x**2
        lists.append(kv_x)

print(lists)


# ✨ Бонус (подготовка к Telegram-ботам):
